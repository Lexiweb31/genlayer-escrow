import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contracts = {
  bountyContractSource: "bounty_escrow.py",
  freelanceContractSource: "freelance_escrow.py",
};

const exports = await Promise.all(Object.entries(contracts).map(async ([name, filename]) => {
  const source = await readFile(path.join(projectRoot, "contracts", filename), "utf8");
  return `export const ${name} = ${JSON.stringify(source)};`;
}));

const output = [
  "// Generated by scripts/generate-contract-sources.mjs. Do not edit by hand.",
  ...exports,
].join("\n\n") + "\n";

await writeFile(path.join(projectRoot, "lib", "server", "contract-sources.generated.ts"), output);
